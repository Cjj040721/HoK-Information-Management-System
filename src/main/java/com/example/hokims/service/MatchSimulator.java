package com.example.hokims.service;

import com.example.hokims.combat.CombatReport;
import com.example.hokims.combat.TurnBasedEngine;
import com.example.hokims.model.Team;

/**
 * Singleton-style enum used to simulate combat matches between two teams.
 */
public enum MatchSimulator {
    INSTANCE;

    // Core engine that handles the turn-based simulation logic
    private final TurnBasedEngine engine = new TurnBasedEngine();

    /**
     * Simulates a match between two teams using the default maximum of 50 rounds.
     *
     * @param a Team A
     * @param b Team B
     * @return the combat report generated by the simulation
     */
    public CombatReport simulate(Team a, Team b) {
        return simulate(a, b, 50);
    }

    /**
     * Simulates a match between two teams with a specified maximum number of rounds.
     *
     * @param a          Team A
     * @param b          Team B
     * @param maxRounds  Maximum number of rounds allowed in the simulation
     * @return the combat report generated by the simulation
     * @throws IllegalArgumentException if either team is null
     */
    public CombatReport simulate(Team a, Team b, int maxRounds) {
        if (a == null || b == null) throw new IllegalArgumentException("team null");
        return engine.simulate(a, b, maxRounds);
    }
}
